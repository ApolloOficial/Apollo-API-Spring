package org.apollo.api.sungrow;

import java.time.Clock;
import java.time.LocalDateTime;
import java.time.ZoneId;
import java.time.ZonedDateTime;
import java.time.format.DateTimeFormatter;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.HashSet;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Random;
import java.util.Set;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.stereotype.Component;

@Component
@ConditionalOnSungrowSimulated
public class SungrowSimulatedPlant implements SungrowRealTimeSource {
    private static final Logger log = LoggerFactory.getLogger(SungrowSimulatedPlant.class);
    private static final DateTimeFormatter DEVICE_TIME = DateTimeFormatter.ofPattern("yyyyMMddHHmmss");
    private static final Map<Integer, int[]> POINTS = new HashMap<>();

    static {
        for (int n = 1; n <= SungrowPointMapper.MAX_STRINGS; n++) {
            POINTS.put(SungrowPointMapper.voltagePoint(n), new int[] {n, 0});
            POINTS.put(SungrowPointMapper.currentPoint(n), new int[] {n, 1});
        }
    }

    private final SungrowProperties properties;
    private final Clock clock;
    private final Set<String> faultySerials = new HashSet<>();
    private final Map<String, Double> weakStrings = new HashMap<>();

    @Autowired
    public SungrowSimulatedPlant(SungrowProperties properties) {
        this(properties, Clock.system(ZoneId.of(properties.getDeviceTimeZone())));
    }

    SungrowSimulatedPlant(SungrowProperties properties, Clock clock) {
        this.properties = properties;
        this.clock = clock;
        for (String serial : split(properties.getSimulationFaultSerials())) {
            faultySerials.add(serial);
        }
        for (String item : split(properties.getSimulationWeakStrings())) {
            String[] parts = item.split(":");
            if (parts.length != 3) {
                throw new IllegalStateException("apollo.sungrow.simulation-weak-strings must look like SERIAL:STRING:FACTOR");
            }
            weakStrings.put(parts[0].trim() + ":" + parts[1].trim(), Double.parseDouble(parts[2].trim()));
        }
        log.warn("Sungrow plant is SIMULATED: readings are generated by the API itself, nothing is read from Sungrow");
    }

    @Override
    public List<Map<String, Object>> realTime(List<String> serialNumbers, List<String> pointIds) {
        ZonedDateTime now = ZonedDateTime.now(clock);
        int step = Math.max(1, properties.getSimulationStepMinutes());
        int bucket = ((now.getHour() * 60 + now.getMinute()) / step) * step;
        LocalDateTime deviceTime = now.toLocalDate().atTime(bucket / 60, bucket % 60);
        double sun = properties.isSimulationAlwaysSun() ? 1.0 : sun(bucket);

        List<Map<String, Object>> devices = new ArrayList<>();
        for (String serial : serialNumbers) {
            Map<String, Object> device = new LinkedHashMap<>();
            device.put("device_sn", serial);
            device.put("device_time", deviceTime.format(DEVICE_TIME));
            device.put("dev_status", sun > 0 ? "1" : "0");
            device.put("dev_fault_status", faultySerials.contains(serial) ? "1" : "4");
            for (String pointId : pointIds) {
                int[] ref = point(pointId);
                if (ref != null) {
                    device.put("p" + pointId, String.format(Locale.ROOT, "%.1f",
                            value(serial, ref[0], ref[1], sun, bucket)));
                }
            }
            devices.add(device);
        }
        return devices;
    }

    private static int[] point(String pointId) {
        try {
            return POINTS.get(Integer.parseInt(pointId.trim()));
        } catch (NumberFormatException exception) {
            return null;
        }
    }

    private static double sun(int minuteOfDay) {
        double hour = minuteOfDay / 60.0;
        return hour <= 6 || hour >= 18 ? 0 : Math.sin(Math.PI * (hour - 6) / 12);
    }

    private double value(String serial, int stringNumber, int kind, double sun, int bucket) {
        if (sun <= 0.02) {
            return 0;
        }
        double stringFactor = 0.93 + new Random((serial + "#" + stringNumber).hashCode()).nextDouble() * 0.07;
        double weakFactor = weakStrings.getOrDefault(serial + ":" + stringNumber, 1.0);
        double noise = 1 + (new Random(31L * bucket + stringNumber).nextDouble() - 0.5) * 0.04;
        if (kind == 0) {
            return (470 + 110 * sun) * (0.98 + 0.02 * stringFactor) * noise;
        }
        return 10.5 * sun * stringFactor * weakFactor * noise;
    }

    private static List<String> split(String csv) {
        List<String> items = new ArrayList<>();
        if (csv != null) {
            for (String item : csv.split(",")) {
                if (!item.isBlank()) {
                    items.add(item.trim());
                }
            }
        }
        return items;
    }
}
